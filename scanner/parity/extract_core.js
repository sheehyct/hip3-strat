"use strict";
// Extracts the STRAT-CORE block from hip3_strat_screener.html (repo root)
// into strat_core_extracted.js with module.exports appended.
// The dashboard HTML remains the single source of truth;
// this script never edits the core, it only slices it out between the markers.
// Zero dependencies - node builtins only.
//
// review MEDIUM-6: exposes build() so run_parity.js can derive the
// expected module in memory and byte-compare it to the committed copy BEFORE
// loading it (the harness previously require()d the committed file blind and
// could certify stale JavaScript). --check mode compares without writing.

var fs = require("fs");
var path = require("path");

var HTML = path.resolve(__dirname, "..", "hip3_strat_screener.html");
var OUT = path.join(__dirname, "strat_core_extracted.js");

var BEGIN = "// ==== STRAT-CORE-BEGIN ====";
var END = "// ==== STRAT-CORE-END ====";

function build(htmlPath) {
  var src = fs.readFileSync(htmlPath || HTML, "utf8");
  var a = src.indexOf(BEGIN);
  var b = src.indexOf(END);
  if (a < 0 || b < 0 || b <= a) {
    throw new Error("STRAT-CORE markers not found in " + (htmlPath || HTML));
  }
  var core = src.slice(a, b + END.length);
  return (
    '"use strict";\n' +
    "// AUTO-GENERATED by extract_core.js - do not edit. Source of truth:\n" +
    "// hip3_strat_screener.html between STRAT-CORE-BEGIN / STRAT-CORE-END.\n" +
    core +
    "\n\nmodule.exports = {\n" +
    "  classify: classify,\n" +
    "  classifySeries: classifySeries,\n" +
    "  detectCompleted: detectCompleted,\n" +
    "  analyzeTF: analyzeTF,\n" +
    "  weekStart: weekStart,\n" +
    "  monthStart: monthStart,\n" +
    "  nextMonthStart: nextMonthStart,\n" +
    "  aggregateBars: aggregateBars,\n" +
    "  targetVersion: targetVersion\n" +
    "};\n"
  );
}

function main() {
  var out = build();
  if (process.argv.indexOf("--check") >= 0) {
    var committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
    if (committed !== out) {
      console.error(
        "parity extraction STALE: parity/strat_core_extracted.js does not " +
          "match the HTML. Regenerate: node parity/extract_core.js"
      );
      process.exit(1);
    }
    console.log("parity extraction matches the HTML (" + out.length + " bytes)");
    return;
  }
  fs.writeFileSync(OUT, out);
  console.log("extracted STRAT core -> " + OUT + " (" + out.length + " bytes)");
}

if (require.main === module) main();

module.exports = { build: build, OUT: OUT, HTML: HTML };
